const english = { 'contact.copied': 'Address copied', 'cursor.open': 'Open', 'lang.announce': 'Language: English' };
const bindings = [
    ['data-i18n', (el, value) => { el.textContent = value; }, (el) => el.textContent],
    ['data-i18n-aria', (el, value) => el.setAttribute('aria-label', value), (el) => el.getAttribute('aria-label')],
    ['data-i18n-alt', (el, value) => el.setAttribute('alt', value), (el) => el.getAttribute('alt')],
    ['data-i18n-title', (el, value) => el.setAttribute('title', value), (el) => el.getAttribute('title')]
];

let language = 'en';

export function getLanguage() {
    return language;
}

export function t(key) {
    return (language === 'sl' ? sl[key] : english[key]) || english[key] || key;
}

function remember(key, value) {
    if (!(key in english)) english[key] = value;
}

function apply() {
    bindings.forEach(([attribute, write, read]) => {
        document.querySelectorAll('[' + attribute + ']').forEach((el) => {
            const key = el.getAttribute(attribute);
            remember(key, read(el));
            write(el, t(key));
        });
    });

    // Sub-pages carry data-page and their own title and description keys.
    const page = document.documentElement.dataset.page;
    const suffix = page ? '.' + page : '';
    const description = document.querySelector('meta[name="description"]');
    remember('meta.title' + suffix, document.title);
    document.title = t('meta.title' + suffix);
    if (description) {
        remember('meta.description' + suffix, description.content);
        description.content = t('meta.description' + suffix);
    }

    document.documentElement.lang = language;
    document.querySelectorAll('[data-lang-toggle]').forEach((button) => {
        button.textContent = language === 'sl' ? 'English' : 'Slovensko';
        button.lang = language === 'sl' ? 'en' : 'sl';
    });
}

export function setLanguage(next, announce) {
    language = next === 'sl' ? 'sl' : 'en';
    apply();
    try { localStorage.setItem('language', language); } catch (error) { /* private mode: not remembered */ }
    if (announce) {
        const status = document.getElementById('langStatus');
        if (status) status.textContent = t('lang.announce');
    }
    document.dispatchEvent(new CustomEvent('i18n:change'));
}

let stored = null;
try { stored = localStorage.getItem('language'); } catch (error) { /* ignore */ }
const requested = new URLSearchParams(location.search).get('lang') || stored;
if (requested === 'sl') setLanguage('sl');

// ?lang=sl is the address search engines get for the Slovenian version.
const canonical = document.querySelector('link[rel="canonical"]');
if (canonical && new URLSearchParams(location.search).get('lang') === 'sl') canonical.href += '?lang=sl';

document.querySelectorAll('[data-lang-toggle]').forEach((button) => {
    button.addEventListener('click', () => setLanguage(language === 'sl' ? 'en' : 'sl', true));
});
